export type DietaryRestriction =
  | 'Vegetarian'
  | 'Vegan'
  | 'Keto'
  | 'Gluten-Free'
  | 'Dairy-Free'
  | 'High-Protein';

export type DifficultyLevel = 'Easy' | 'Medium' | 'Hard';

/** Fridge-inventory categories (Phase 1 §2C). */
export type FridgeCategory =
  | 'Vegetables'
  | 'Fruits'
  | 'Dairy'
  | 'Meat'
  | 'Seafood'
  | 'Grains'
  | 'Spices'
  | 'Beverages'
  | 'Other';

/**
 * One item in the user's fridge inventory.
 * `expiresAt` is an ISO date string (YYYY-MM-DD) or null — the data-model
 * hook for Phase 3 expiry tracking; the UI exposes it in the ingredient
 * editor. `source` distinguishes AI-scanned items from manual ones.
 */
export interface FridgeIngredient {
  id: string;
  name: string;
  quantity?: string;
  category: FridgeCategory;
  source: 'scan' | 'manual';
  addedAt: number;
  expiresAt?: string | null;
}

export interface IngredientItem {
  name: string;
  amount: string;
  essential: boolean;
  inFridge: boolean;
}

/**
 * Optional per-serving nutrition. Only shown when present — the app never
 * invents macros. Seed and AI recipes ship without it; a future nutrition
 * data source (or the AI prompt) can fill it in and the UI will display it.
 * All values are per serving, matching `Recipe.calories`.
 */
export interface RecipeNutrition {
  proteinGrams?: number;
  carbsGrams?: number;
  fatGrams?: number;
  fiberGrams?: number;
  sodiumMg?: number;
}

export interface RecipeStep {
  stepNumber: number;
  instruction: string;
  tip?: string;
  durationMinutes?: number;
}

export interface Recipe {
  id: string;
  title: string;
  description: string;
  difficulty: DifficultyLevel;
  prepTimeMinutes: number;
  cookTimeMinutes: number;
  calories: number;
  servings: number;
  /** Per-serving macros — shown only when present, never invented. */
  nutrition?: RecipeNutrition;
  dietaryTags: DietaryRestriction[];
  /** Only set when the photo genuinely depicts this dish. AI-generated
   * recipes have no imageUrl — the card renders a clean text-only header
   * instead of a misleading stock photo (QA P0-4). */
  imageUrl?: string;
  /** True for recipes generated by the AI endpoints; false/undefined for
   * the curated sample recipes shipped with the app. */
  isAiGenerated?: boolean;
  ingredients: IngredientItem[];
  steps: RecipeStep[];
}

export interface ShoppingListItem {
  id: string;
  name: string;
  amount: string;
  category?: FridgeCategory;
  sourceRecipe?: string;
  checked: boolean;
  addedAt: number;
}

export interface FilterState {
  dietary: DietaryRestriction[];
  maxPrepTime: number | null;
  difficulty: DifficultyLevel | 'All';
  searchQuery: string;
}

/**
 * One persisted scan — the unit stored in versioned localStorage
 * (`mise_last_scan_v1` / `mise_scan_history_v1`) and the shape a future
 * database-backed scan record will use. `thumbnail` is a small (≤512 px)
 * JPEG data URL of the scanned photo, kept only on the latest scan.
 */
export interface ScanRecord {
  id: string;
  scannedAt: number;
  summary: string;
  ingredients: FridgeIngredient[];
  recipes: Recipe[];
  thumbnail?: string | null;
}

export interface FridgeAnalysisResponse {
  detectedIngredients: string[];
  summary: string;
  recipes: Recipe[];
}

/**
 * One named fridge. The app used to have a single implicit inventory;
 * multiple fridges are stored as profiles so a household can keep e.g.
 * "Home Fridge" and "Garage Fridge" separate. Each profile owns its own
 * ingredient list; scans apply to the active profile.
 */
export interface FridgeProfile {
  id: string;
  name: string;
  ingredients: FridgeIngredient[];
  createdAt: number;
}

/** Days of the week, Monday-first, for the meal planner. */
export const WEEK_DAYS = [
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
  'Sunday',
] as const;

export type WeekDay = (typeof WEEK_DAYS)[number];

/** One planned meal: a recipe plus the servings it is cooked for. */
export interface PlannedMeal {
  recipeId: string;
  servings: number;
}

/** A week of planned meals — a day with no entry has nothing planned. */
export type MealPlan = Partial<Record<WeekDay, PlannedMeal>>;
